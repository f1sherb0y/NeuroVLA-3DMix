#!/bin/bash
# =============================================================================
# LIBERO Evaluation Script for NeuroVLA
#
# Loads a NeuroVLA checkpoint and evaluates on one or all LIBERO task suites.
# Optionally enables online R-STDP test-time adaptation on the SNN head.
#
# Usage:
#   bash run_eval_libero.sh --pretrained <ckpt>                         # default: libero_goal, 10 trials
#   bash run_eval_libero.sh --pretrained <ckpt> --suite libero_spatial
#   bash run_eval_libero.sh --pretrained <ckpt> --suite all             # run all 4 suites
#   bash run_eval_libero.sh --pretrained <ckpt> --trials 50 --gpu 1
#   bash run_eval_libero.sh --pretrained <ckpt> --online-stdp            # enable online STDP
#   bash run_eval_libero.sh --pretrained <ckpt> --dry-run                # validate only
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$(dirname "$SCRIPT_DIR")")"
cd "$PROJECT_ROOT"

# Generated by scripts/setup_neurovla_env.sh. A user-maintained .env is loaded
# afterwards so explicit local/server settings take precedence.
[ -f .env.libero ] && { set -a; source .env.libero; set +a; }
[ -f .env ] && { set -a; source .env; set +a; }

# ---------- defaults ----------
PRETRAINED=""
SUITE="libero_goal"
TRIALS="${NUM_TRIALS:-10}"
SEED="${SEED:-7}"
GPU="${CUDA_VISIBLE_DEVICES:-0}"
VIDEO_OUT="${VIDEO_OUT:-results/evaluation/brain_inspired_eval_$(date +%Y%m%d_%H%M%S)}"
ONLINE_STDP=false
DRY_RUN=false
CONDA_ENV="${CONDA_ENV:-neurovla}"

# Online STDP defaults (only used if --online-stdp)
STDP_LR="${STDP_LR:-5e-5}"
STDP_WARMUP="${STDP_WARMUP:-0}"
STDP_MAX_DEV="${STDP_MAX_DEV:-0.2}"
STDP_ROLLBACK="${STDP_ROLLBACK:-0.5}"
STDP_RESET_PER_TASK=true

# ---------- parse CLI ----------
while [[ $# -gt 0 ]]; do
    case "$1" in
        --pretrained|--ckpt) PRETRAINED="$2"; shift 2 ;;
        --suite)             SUITE="$2"; shift 2 ;;
        --trials)            TRIALS="$2"; shift 2 ;;
        --seed)              SEED="$2"; shift 2 ;;
        --gpu)               GPU="$2"; shift 2 ;;
        --video-out)         VIDEO_OUT="$2"; shift 2 ;;
        --online-stdp)       ONLINE_STDP=true; shift ;;
        --dry-run)           DRY_RUN=true; shift ;;
        *) echo "Unknown arg: $1"; exit 1 ;;
    esac
done

if [ -z "$PRETRAINED" ]; then
    echo "ERROR: --pretrained <checkpoint_path> is required"
    exit 1
fi

[ -e "$PRETRAINED" ] || { echo "ERROR: checkpoint does not exist: $PRETRAINED" >&2; exit 1; }
: "${LIBERO_HOME:?set LIBERO_HOME or run: bash scripts/setup_neurovla_env.sh}"
LIBERO_CONFIG_PATH="${LIBERO_CONFIG_PATH:-$PROJECT_ROOT/.libero}"
[ -f "$LIBERO_CONFIG_PATH/config.yaml" ] || {
    echo "ERROR: LIBERO config not found: $LIBERO_CONFIG_PATH/config.yaml" >&2
    echo "Run: bash scripts/setup_neurovla_env.sh" >&2
    exit 1
}

MUJOCO_GL="${MUJOCO_GL:-egl}"
MUJOCO_EGL_DEVICE_ID="${MUJOCO_EGL_DEVICE_ID:-$GPU}"

export CUDA_VISIBLE_DEVICES="$GPU"
export LIBERO_HOME LIBERO_CONFIG_PATH MUJOCO_GL MUJOCO_EGL_DEVICE_ID
export PYTHONPATH="${PROJECT_ROOT}:${LIBERO_HOME}${PYTHONPATH:+:$PYTHONPATH}"

# Resolve one concrete interpreter up front. This works for Conda installations
# outside /root and /opt and keeps result parsing on the same environment.
ENV_PY="${NEUROVLA_PYTHON:-}"
if [ -z "$ENV_PY" ] && [ "${CONDA_DEFAULT_ENV:-}" = "$CONDA_ENV" ]; then
    ENV_PY="$(command -v python)"
fi
if [ -z "$ENV_PY" ] && command -v conda >/dev/null 2>&1; then
    ENV_PY="$(conda run -n "$CONDA_ENV" python -c 'import sys; print(sys.executable)' | awk 'NF {line=$0} END {print line}')"
fi
[ -n "$ENV_PY" ] && [ -x "$ENV_PY" ] || {
    echo "ERROR: cannot resolve Python for Conda environment: $CONDA_ENV" >&2
    exit 1
}

# ---------- expand suite list ----------
if [ "$SUITE" = "all" ]; then
    SUITES=(libero_goal libero_spatial libero_object libero_10)
else
    SUITES=("$SUITE")
fi

# ---------- per-suite eval loop ----------
for S in "${SUITES[@]}"; do
    OUT_DIR="${VIDEO_OUT}/${S}"
    [ "$DRY_RUN" = true ] || mkdir -p "$OUT_DIR"

    echo "=============================================="
    echo "  LIBERO Eval — NeuroVLA"
    echo "  Suite:        $S"
    echo "  Checkpoint:   $PRETRAINED"
    echo "  Trials/task:  $TRIALS"
    echo "  GPU:          $GPU"
    echo "  Online STDP:  $ONLINE_STDP"
    echo "  Output:       $OUT_DIR"
    echo "=============================================="

    CMD=(
        benchmarks/LIBERO/eval/eval_libero_online_stdp.py
        --pretrained-path "$PRETRAINED"
        --task-suite-name "$S"
        --num-trials-per-task "$TRIALS"
        --video-out-path "$OUT_DIR"
        --seed "$SEED"
    )

    if [ "$ONLINE_STDP" = true ]; then
        CMD+=(
            --stdp-lr "$STDP_LR"
            --stdp-warmup-episodes "$STDP_WARMUP"
            --stdp-max-deviation "$STDP_MAX_DEV"
            --stdp-rollback-shrink "$STDP_ROLLBACK"
        )
        [ "$STDP_RESET_PER_TASK" = true ] && CMD+=(--stdp-reset-per-task)
    else
        CMD+=(--no-stdp)
    fi

    if [ "$DRY_RUN" = true ]; then
        printf 'Dry-run command:'
        printf ' %q' "$ENV_PY" "${CMD[@]}"
        printf '\n'
        continue
    fi

    "$ENV_PY" "${CMD[@]}"

    # Print summary
    if [ -f "$OUT_DIR/eval_results.json" ]; then
        SR=$("$ENV_PY" -c "import json,sys; d=json.load(open(sys.argv[1])); print(f'{d[\"success_rate\"]*100:.1f}%')" "$OUT_DIR/eval_results.json" 2>/dev/null || echo ERR)
        echo ">>> $S success rate: $SR"
    fi
done

echo ""
echo "=============================================="
echo "  All evaluations done"
echo "  Output root: $VIDEO_OUT"
echo "=============================================="
